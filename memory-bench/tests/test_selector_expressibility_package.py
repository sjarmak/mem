"""Seal and regeneration tests for the mem-rj2mg selector-expressibility package.

The package is a sealed artifact: manifest.json pins a sha256 over every other
file, so a locator that drifts cannot be fixed by editing a sealed file in place
(that breaks the seal to fix a pointer). It has to be regenerated by re-running
package.py. These tests hold the properties that make that safe: the seal
verifies against the tree as committed, the packager refuses to seal anything it
should not, and re-running it reproduces the committed bytes exactly.

Two disciplines this file follows because reviewers caught it not following them.
Every guard is exercised through the code path production uses, never a
reimplementation, so deleting a guard reds a test. And the leak detector, which
several assertions consume, carries its own positive and negative controls: a
scanner that silently matches nothing would otherwise make every test that
depends on it pass by construction.

Filed under mem-8zgnn, after mem-vn4ek moved the preregistration out of
fixtures/bdp/ (the tree handed to BDP) and the three references to its old path
were deliberately left unedited.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import shutil
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path
from types import ModuleType

import pytest

from tests.paths import REPO, REPO_ROOT

PKG = REPO / "results" / "bdp" / "selector-expressibility"
PREREG = REPO / "results" / "bdp" / "selector-expressibility-preregistration.json"
STALE_PREREG_PATH = "fixtures/bdp/selector-expressibility-preregistration.json"


def _load_packager() -> ModuleType:
    """Import package.py without leaving bytecode inside the sealed directory.

    exec_module writes __pycache__/package.cpython-*.pyc next to the source, and
    that file embeds the absolute path of this checkout. It is gitignored, so it
    never reaches a commit, but it does reach any tar or rsync of the directory,
    which is the publication act this package exists to make safe.
    """
    spec = importlib.util.spec_from_file_location("rj2mg_package", PKG / "package.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    previous = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    return module


packager = _load_packager()


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _run_packager(out: Path, scratch: Path) -> subprocess.CompletedProcess[str]:
    """Invoke the packager the way an operator does, surfacing its own message.

    check=True would hide the packager's diagnostic inside CalledProcessError and
    report CPython's subprocess internals instead, which is the swallowed-output
    defect this repo treats as a bug in its own right.
    """
    return subprocess.run(
        [sys.executable, str(PKG / "package.py"), str(out), str(scratch)],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )


@pytest.fixture
def staged(tmp_path: Path) -> Iterator[Path]:
    """A complete, valid copy of the package, ready to be regenerated into."""
    out = tmp_path / "package"
    shutil.copytree(PKG, out)
    yield out


# --- the detector's own controls ------------------------------------------------
#
# Every assertion below that consumes LEAK or leak_locations is only as good as
# these. A scanner that matches nothing satisfies every "assert no leaks" by
# construction, and makes the disclosure test early-return as though the document
# were clean.


@pytest.mark.parametrize(
    "sample",
    [
        "/home/someone/gas-city",
        "/Users/someone/Desktop/notes",
        "/root/secrets",
        "/srv/agents/someone/run",
        r"C:\Users\someone\secret.txt",
        r"\\fileserver\share\someone",
        "~/gas-city/city.toml",
        "~someone/scratch",
        "$HOME/keys",
        "${HOME}/keys",
        "someone@example.com",
        "SOMEONE@EXAMPLE.COM",
        "first.last+tag@sub.example.co.uk",
    ],
)
def test_leak_detector_matches_known_leaks(sample: str) -> None:
    assert packager.LEAK.search(sample), f"detector missed {sample!r}"


@pytest.mark.parametrize(
    "sample",
    [
        "mem-8zgnn",
        "memory-bench/results/bdp/selector-expressibility",
        "src/ingest/trace-resolve.ts",
        "bd list --status open",
        "3ffc83e06bc22216e135ca2b2a3b24b8278b99ba1bb1310c1dcae7890e4aeb35",
        "https://github.com/gastownhall/bdp/issues/8",
        "G1 lands at 0.0114 session-averaged",
    ],
)
def test_leak_detector_does_not_fire_on_ordinary_content(sample: str) -> None:
    assert not packager.LEAK.search(sample), f"detector false-positived on {sample!r}"


def test_leak_locations_reports_pointers_not_leaf_names() -> None:
    document = {
        "a": {"procedure": "run from /home/someone/x"},
        "b": {"procedure": "also /home/someone/y"},
        "c": ["clean", "~someone/z"],
        "/home/someone/as-a-key": "clean",
        "d": {"nested": [{"deep": "$HOME/w"}]},
        "e": "clean",
        "f": 3,
        "g": None,
    }
    assert sorted(packager.leak_locations(document)) == [
        "/a/procedure",
        "/b/procedure",
        "/c/1",
        "/d/nested/0/deep",
        "/~1home~1someone~1as-a-key",
    ]


def test_leak_locations_is_empty_on_clean_and_empty_documents() -> None:
    assert packager.leak_locations({}) == []
    assert packager.leak_locations([]) == []
    assert packager.leak_locations({"a": {"b": ["clean", 1, None]}}) == []


# --- the committed artifact -----------------------------------------------------


def test_manifest_seal_verifies_against_the_committed_tree() -> None:
    manifest = json.loads((PKG / "manifest.json").read_text())
    for name, record in manifest["files"].items():
        path = PKG / name
        assert path.is_file(), f"{name} is pinned by the manifest but missing"
        assert _digest(path) == record["sha256"], f"{name} digest does not match the seal"
        assert path.stat().st_size == record["bytes"], f"{name} size does not match the seal"


def test_the_committed_package_is_exactly_the_sealed_set() -> None:
    """The producer's own contents guard, applied to the committed directory."""
    packager.verify_sealed_contents(PKG)
    manifest = json.loads((PKG / "manifest.json").read_text())
    assert set(manifest["files"]) == packager.SEALED - {"manifest.json"}


def test_recorded_preregistration_path_resolves_and_matches_the_pinned_digest() -> None:
    analysis = json.loads((PKG / "analysis.json").read_text())
    manifest = json.loads((PKG / "manifest.json").read_text())
    recorded = REPO_ROOT / analysis["preregistration"]["path"]
    assert recorded.is_file(), "analysis.json names a preregistration path that does not exist"
    assert _digest(recorded) == manifest["preregistration_sha256"]
    assert analysis["preregistration"]["sha256"] == manifest["preregistration_sha256"]


def test_no_sealed_file_still_points_at_the_moved_preregistration() -> None:
    """All three repaired references, not just the one in analysis.json.

    classify.py's docstring and package.py's own constants are as publishable as
    the JSON, and a revert of any of them is the regression mem-8zgnn tracked.
    """
    for name in sorted(packager.SEALED):
        text = (PKG / name).read_text()
        for line_number, line in enumerate(text.splitlines(), 1):
            if STALE_PREREG_PATH not in line:
                continue
            assert "PREREG_LOCKED_PATH" in line or "locked_at_path" in line, (
                f"{name}:{line_number} points at the moved preregistration path "
                f"outside the two constants that record it deliberately"
            )


def test_locked_commit_agrees_with_the_report() -> None:
    """analysis.json and report.md must name the same lock commit.

    They did not: package.py stamped `git rev-parse HEAD` at packaging time, so
    analysis.json recorded the commit that carried the first result rather than
    the commit the preregistration was locked at, which report.md names.
    """
    analysis = json.loads((PKG / "analysis.json").read_text())
    report = (PKG / "report.md").read_text()
    locked = analysis["preregistration"]["locked_commit"]
    assert f"`{locked[:7]}`" in report, "report.md names a different lock commit"


def test_no_package_file_carries_a_local_path_or_an_identity() -> None:
    """The producer's leak guard, applied to the committed directory.

    This checks two of the manifest's privacy clauses, the mechanically checkable
    ones: absolute local paths and addresses. The remaining clauses (no query
    literals, free-text arguments, bead titles or bodies, model text) hold by
    construction upstream in classify.py, which never carries an argument value
    into a count, and no scan here establishes them.
    """
    packager.verify_no_leaks(PKG)


def test_the_disclosure_matches_the_document_it_describes() -> None:
    """Bidirectional: every leak is disclosed and every disclosure still resolves.

    A leak in a locked document gets disclosed, never edited out, because editing
    would break the digest the whole package rests on. The disclosure records RFC
    6901 pointers rather than the values, or it would carry the leak into the
    package that warns about it.
    """
    disclosed = json.loads((PKG / "analysis.json").read_text())["preregistration"]["not_redacted"]
    actual = packager.leak_locations(json.loads(PREREG.read_text()))
    assert sorted(disclosed["locations"]) == sorted(actual)
    for pointer in disclosed["locations"]:
        assert pointer in actual, f"{pointer} is disclosed but no longer resolves to a leak"


# --- the guards, exercised through production -----------------------------------


def test_verify_preregistration_accepts_the_real_tree() -> None:
    packager.verify_preregistration(REPO_ROOT)


def test_verify_preregistration_rejects_mutated_bytes(tmp_path: Path) -> None:
    staged_file = tmp_path / packager.PREREG_PATH
    staged_file.parent.mkdir(parents=True)
    staged_file.write_bytes(PREREG.read_bytes() + b" ")
    with pytest.raises(packager.PackageIntegrityError) as excinfo:
        packager.verify_preregistration(tmp_path)
    assert f"at {packager.PREREG_PATH} hashes" in str(excinfo.value)


def test_verify_preregistration_rejects_a_missing_preregistration(tmp_path: Path) -> None:
    with pytest.raises(packager.PackageIntegrityError) as excinfo:
        packager.verify_preregistration(tmp_path)
    assert "not found" in str(excinfo.value)


def test_verify_preregistration_rejects_a_wrong_historical_blob(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The lock-commit half of the guard, which nothing pinned before.

    Point the constants at a path that exists at the lock commit but holds other
    bytes. The on-disk digest still passes; only the historical check can refuse.
    """
    monkeypatch.setattr(
        packager,
        "PREREG_LOCKED_PATH",
        "memory-bench/results/beads_ordering/preregistration.json",
    )
    with pytest.raises(packager.PackageIntegrityError) as excinfo:
        packager.verify_preregistration(REPO_ROOT)
    message = str(excinfo.value)
    assert f"at {packager.PREREG_LOCKED_COMMIT} hashes" in message
    assert "could not read" not in message, "a content mismatch was reported as a fault"


def test_a_git_fault_is_reported_as_a_fault_not_a_mismatch(tmp_path: Path) -> None:
    """A non-zero git exit must never be read as a digest verdict.

    A directory that is not a repository makes `git show` exit 128. The guard has
    to say it could not check, and carry git's own reason.
    """
    staged_file = tmp_path / packager.PREREG_PATH
    staged_file.parent.mkdir(parents=True)
    staged_file.write_bytes(PREREG.read_bytes())
    with pytest.raises(packager.PackageIntegrityError) as excinfo:
        packager.verify_preregistration(tmp_path)
    message = str(excinfo.value)
    assert "could not read the locked preregistration" in message
    assert "hashes" not in message, "a fault was reported as a content mismatch"
    assert "not a git repository" in message, "git's own stderr was swallowed"


def test_verify_results_rejects_a_changed_published_number() -> None:
    """The packager may not re-seal numbers other than the published ones.

    Without this the manifest would prove only that it sealed whatever it was
    handed: package.py takes the analysis on an arbitrary scratch path, copies it,
    and then mints the digests that verify it.
    """
    analysis = json.loads((PKG / "analysis.json").read_text())
    analysis["gates"] = {"tampered": True}
    with pytest.raises(packager.PackageIntegrityError) as excinfo:
        packager.verify_results(REPO_ROOT, analysis)
    assert "result keys hash" in str(excinfo.value)


def test_verify_results_rejects_a_retuned_constant(monkeypatch: pytest.MonkeyPatch) -> None:
    """Changing RESULTS_SHA alone must not admit a different result.

    The published blob is checked too, so the constant and history have to agree.
    """
    analysis = json.loads((PKG / "analysis.json").read_text())
    analysis["gates"] = {"tampered": True}
    monkeypatch.setattr(
        packager,
        "RESULTS_SHA",
        packager.canonical_digest({k: analysis[k] for k in packager.RESULT_KEYS}),
    )
    with pytest.raises(packager.PackageIntegrityError) as excinfo:
        packager.verify_results(REPO_ROOT, analysis)
    assert f"published results at {packager.RESULTS_COMMIT} hash" in str(excinfo.value)


def test_verify_results_accepts_the_committed_analysis() -> None:
    packager.verify_results(REPO_ROOT, json.loads((PKG / "analysis.json").read_text()))


# --- the packaging command itself -----------------------------------------------


def test_packaging_refuses_an_incomplete_output_directory(tmp_path: Path) -> None:
    """report.md is hand-authored and never emitted, so an empty out drops it.

    Before this guard the packager exited 0 with a five-file manifest, producing
    an internally consistent seal over an incomplete package.
    """
    out = tmp_path / "out"
    out.mkdir()
    done = _run_packager(out, PKG)
    assert done.returncode != 0, done.stdout
    assert "refusing to seal an incomplete package" in done.stderr
    assert "report.md" in done.stderr
    assert not (out / "manifest.json").exists(), "a manifest was written anyway"


def test_packaging_refuses_an_unexpected_file(staged: Path) -> None:
    """Anything in the directory is hashed into the manifest and shipped."""
    (staged / "notes.txt").write_text("scratch\n")
    done = _run_packager(staged, PKG)
    assert done.returncode != 0, done.stdout
    assert "refusing to seal unexpected files" in done.stderr
    assert "notes.txt" in done.stderr


def test_packaging_refuses_a_leak_in_a_sealed_file(staged: Path) -> None:
    (staged / "report.md").write_text(
        (staged / "report.md").read_text() + "\nrun from /home/someone/gas-city\n"
    )
    done = _run_packager(staged, PKG)
    assert done.returncode != 0, done.stdout
    assert "refusing to seal report.md" in done.stderr


def test_packaging_refuses_a_tampered_scratch_analysis(staged: Path, tmp_path: Path) -> None:
    """The guard's wiring into main(), not only the guard.

    Deleting the verify_* calls from main() must red a test. Exercising the
    verifiers directly cannot catch that, which is how an earlier version of this
    file left the whole command untested.
    """
    scratch = tmp_path / "scratch"
    shutil.copytree(PKG, scratch)
    analysis = json.loads((scratch / "analysis.json").read_text())
    analysis["gates"]["G1_search_predicate"]["session_averaged"] = 0.99
    (scratch / "analysis.json").write_text(json.dumps(analysis, indent=2) + "\n")

    done = _run_packager(staged, scratch)
    assert done.returncode != 0, done.stdout
    assert "result keys hash" in done.stderr
    assert json.loads((staged / "analysis.json").read_text())["gates"] != analysis["gates"]


def test_the_copied_script_fails_closed_outside_a_repository(staged: Path) -> None:
    """package.py copies itself into the package, so it runs where publishers unpack it.

    Outside a git checkout it must say what it could not do. It previously died
    with a raw CalledProcessError traceback from repo_root(), twelve lines above
    the guard that carefully converts the same class of fault into a message.
    """
    done = subprocess.run(
        [sys.executable, str(staged / "package.py"), str(staged), str(PKG)],
        cwd=staged,
        capture_output=True,
        text=True,
    )
    assert done.returncode != 0, done.stdout
    assert "could not locate the repository root" in done.stderr
    assert "Traceback" not in done.stderr, "died with a traceback instead of a message"


def test_rerunning_the_packager_reproduces_the_committed_bytes(staged: Path) -> None:
    """The regeneration path mem-8zgnn depends on: re-run, do not hand-edit."""
    done = _run_packager(staged, PKG)
    assert done.returncode == 0, done.stderr

    committed = {p.name for p in PKG.iterdir() if p.is_file()}
    regenerated = {p.name for p in staged.iterdir() if p.is_file()}
    assert regenerated == committed
    for name in sorted(committed):
        assert (staged / name).read_bytes() == (PKG / name).read_bytes(), f"{name} drifted"
