"""Seal and regeneration tests for the mem-rj2mg selector-expressibility package.

The package is a sealed artifact: manifest.json pins a sha256 over every other
file, so a locator that drifts cannot be fixed by editing a sealed file in place
(that breaks the seal to fix a pointer). It has to be regenerated by re-running
package.py. These tests hold the two properties that makes safe: the seal
verifies against the tree as committed, and re-running the packager reproduces
the committed bytes exactly.

Filed under mem-8zgnn, after mem-vn4ek moved the preregistration out of
fixtures/bdp/ (the tree handed to BDP) and the three references to its old path
were deliberately left unedited.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

from tests.paths import REPO, REPO_ROOT

PKG = REPO / "results" / "bdp" / "selector-expressibility"
PREREG = REPO / "results" / "bdp" / "selector-expressibility-preregistration.json"

# Authored by hand, not by package.py, but still hashed into the manifest because
# the manifest covers every file in the output directory. A regeneration that
# forgets to place it drops it from the seal silently.
UNGENERATED = ("report.md",)

# What must not reach a published artifact: an absolute path on the analyst's
# machine, or an email address. Bead ids and repo-relative paths are fine.
LEAK = re.compile(r"/(?:home|Users)/[A-Za-z0-9_.-]+|[A-Za-z0-9_.+-]+@[A-Za-z0-9.-]+\.[a-z]{2,}")


def _load_packager() -> ModuleType:
    spec = importlib.util.spec_from_file_location("rj2mg_package", PKG / "package.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


packager = _load_packager()


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _leaking_fields(node: object, key: str = "") -> set[str]:
    """Field names, at any depth, whose string value carries a local path."""
    if isinstance(node, str):
        return {key} if LEAK.search(node) else set()
    if isinstance(node, dict):
        return set().union(*(_leaking_fields(v, k) for k, v in node.items()), set())
    if isinstance(node, list):
        return set().union(*(_leaking_fields(v, key) for v in node), set())
    return set()


def test_manifest_seal_verifies_against_the_committed_tree() -> None:
    manifest = json.loads((PKG / "manifest.json").read_text())
    for name, record in manifest["files"].items():
        path = PKG / name
        assert path.is_file(), f"{name} is pinned by the manifest but missing"
        assert _digest(path) == record["sha256"], f"{name} digest does not match the seal"
        assert path.stat().st_size == record["bytes"], f"{name} size does not match the seal"


def test_every_package_file_is_covered_by_the_seal() -> None:
    manifest = json.loads((PKG / "manifest.json").read_text())
    on_disk = {p.name for p in PKG.iterdir() if p.is_file() and p.name != "manifest.json"}
    assert on_disk == set(manifest["files"]), "the manifest and the directory disagree"


def test_recorded_preregistration_path_resolves_and_matches_the_pinned_digest() -> None:
    analysis = json.loads((PKG / "analysis.json").read_text())
    manifest = json.loads((PKG / "manifest.json").read_text())
    recorded = REPO_ROOT / analysis["preregistration"]["path"]
    assert recorded.is_file(), "analysis.json names a preregistration path that does not exist"
    assert _digest(recorded) == manifest["preregistration_sha256"]
    assert analysis["preregistration"]["sha256"] == manifest["preregistration_sha256"]


def test_locked_commit_agrees_with_the_report() -> None:
    """analysis.json and report.md must name the same lock commit.

    They did not: package.py stamped `git rev-parse HEAD` at packaging time, so
    analysis.json recorded the commit that carried the first result rather than
    the commit the preregistration was locked at, which report.md names.
    """
    analysis = json.loads((PKG / "analysis.json").read_text())
    report = (PKG / "report.md").read_text()
    locked = analysis["preregistration"]["locked_commit"]
    assert f"`{locked[:7]}`" in report, "report.md names a different lock commit"


def test_the_preregistration_is_byte_identical_at_the_lock_commit() -> None:
    """The bytes at the new path are the bytes that were locked, not a copy."""
    blob = subprocess.run(
        ["git", "show", f"{packager.PREREG_LOCKED_COMMIT}:{packager.PREREG_LOCKED_PATH}"],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
    ).stdout
    assert hashlib.sha256(blob).hexdigest() == packager.PREREG_SHA
    assert _digest(PREREG) == packager.PREREG_SHA


def test_verify_preregistration_accepts_the_real_tree() -> None:
    packager.verify_preregistration(REPO_ROOT)


def test_verify_preregistration_rejects_mutated_bytes(tmp_path: Path) -> None:
    staged = tmp_path / packager.PREREG_PATH
    staged.parent.mkdir(parents=True)
    staged.write_bytes(PREREG.read_bytes() + b" ")
    with pytest.raises(SystemExit) as excinfo:
        packager.verify_preregistration(tmp_path)
    assert "hashes" in str(excinfo.value)


def test_verify_preregistration_rejects_a_missing_preregistration(tmp_path: Path) -> None:
    with pytest.raises(SystemExit) as excinfo:
        packager.verify_preregistration(tmp_path)
    assert "not found" in str(excinfo.value)


def test_no_package_file_carries_a_local_path_or_an_identity() -> None:
    """The manifest's privacy claim, checked instead of asserted.

    It says the package holds no file paths or identities. This is the scan that
    commit 49efed7 was trying to pass when it edited the locked preregistration.
    """
    for path in sorted(p for p in PKG.iterdir() if p.is_file()):
        text = path.read_text()
        hits = LEAK.findall(text)
        assert not hits, f"{path.name} carries {sorted(set(hits))}"


def test_a_local_path_inside_the_locked_preregistration_is_disclosed() -> None:
    """A leak in a locked document gets disclosed, never edited out.

    Editing it would break the digest the whole package rests on, so the only
    honest handling is to name where it sits, in the file a publisher reads. The
    disclosure names fields rather than quoting the value, or it would carry the
    leak into the package it is warning about. If a later preregistration is
    locked clean, this test goes quiet on its own.
    """
    leaking = sorted(_leaking_fields(json.loads(PREREG.read_text())))
    if not leaking:
        return
    disclosed = json.loads((PKG / "analysis.json").read_text())["preregistration"]["not_redacted"]
    assert leaking == sorted(disclosed["fields"]), "the disclosure does not match the document"


def test_rerunning_the_packager_reproduces_the_committed_bytes(tmp_path: Path) -> None:
    """The regeneration path mem-8zgnn depends on: re-run, do not hand-edit."""
    out = tmp_path / "package"
    out.mkdir()
    for name in UNGENERATED:
        shutil.copy2(PKG / name, out / name)

    subprocess.run(
        [sys.executable, str(PKG / "package.py"), str(out), str(PKG)],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
    )

    committed = {p.name for p in PKG.iterdir() if p.is_file()}
    regenerated = {p.name for p in out.iterdir() if p.is_file()}
    assert regenerated == committed
    for name in sorted(committed):
        assert (out / name).read_bytes() == (PKG / name).read_bytes(), f"{name} drifted"
